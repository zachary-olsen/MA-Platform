# Metrics per statement row, computed as of that row's filed_date: the prior-year
# comparison uses the latest version of the prior period filed on or before this row,
# which is normally the comparative column in the same 10-K. Filtering this view on
# filed_date <= D therefore stays point-in-time correct.
#
# Ratios are NULL when the denominator makes them meaningless (e.g. net debt / EBITDA
# with negative EBITDA). Missing debt and short-term investments are treated as zero
# (missing debt is flagged by validation).
METRICS_VIEW = """
CREATE VIEW v_financial_metrics AS
WITH base AS (
    SELECT
        fs.*,
        fs.operating_income + fs.d_and_a AS ebitda,
        fs.cfo - fs.capex AS fcf,
        COALESCE(fs.total_debt, 0) - fs.cash - COALESCE(fs.short_term_investments, 0)
            AS net_debt,
        CASE
            WHEN fs.pretax_income > 0 AND fs.income_tax IS NOT NULL
                THEN LEAST(GREATEST(fs.income_tax / fs.pretax_income, 0), 0.40)
            ELSE 0.21
        END AS tax_rate_for_nopat,
        p1.revenue AS prior_revenue,
        p3.revenue AS prior3_revenue
    FROM financial_statements fs
    LEFT JOIN LATERAL (
        SELECT p.revenue
        FROM financial_statements p
        WHERE p.company_id = fs.company_id
          AND p.period_end BETWEEN fs.period_end - 380 AND fs.period_end - 350
          AND p.filed_date <= fs.filed_date
        ORDER BY p.filed_date DESC, p.accession DESC
        LIMIT 1
    ) p1 ON true
    LEFT JOIN LATERAL (
        SELECT p.revenue
        FROM financial_statements p
        WHERE p.company_id = fs.company_id
          AND p.period_end BETWEEN fs.period_end - 1110 AND fs.period_end - 1080
          AND p.filed_date <= fs.filed_date
        ORDER BY p.filed_date DESC, p.accession DESC
        LIMIT 1
    ) p3 ON true
)
SELECT
    id AS statement_id,
    company_id,
    fiscal_year,
    period_end,
    filed_date,
    accession,
    revenue::float8,
    ebitda::float8,
    fcf::float8,
    net_debt::float8,
    CASE WHEN prior_revenue > 0 THEN revenue / prior_revenue - 1 END::float8 AS revenue_growth,
    CASE WHEN prior3_revenue > 0 AND revenue > 0
        THEN power(revenue / prior3_revenue, 1.0 / 3) - 1 END::float8 AS revenue_cagr_3y,
    (gross_profit / NULLIF(revenue, 0))::float8 AS gross_margin,
    (operating_income / NULLIF(revenue, 0))::float8 AS operating_margin,
    (ebitda / NULLIF(revenue, 0))::float8 AS ebitda_margin,
    (net_income / NULLIF(revenue, 0))::float8 AS net_margin,
    (fcf / NULLIF(revenue, 0))::float8 AS fcf_margin,
    (capex / NULLIF(revenue, 0))::float8 AS capex_to_revenue,
    CASE WHEN net_income > 0 THEN fcf / net_income END::float8 AS fcf_conversion,
    CASE WHEN ebitda > 0 THEN net_debt / ebitda END::float8 AS net_debt_to_ebitda,
    CASE WHEN total_equity > 0 THEN COALESCE(total_debt, 0) / total_equity END::float8
        AS debt_to_equity,
    CASE WHEN interest_expense > 0 THEN operating_income / interest_expense END::float8
        AS interest_coverage,
    CASE WHEN pretax_income > 0 THEN income_tax / pretax_income END::float8
        AS effective_tax_rate,
    CASE WHEN total_equity + net_debt > 0
        THEN operating_income * (1 - tax_rate_for_nopat) / (total_equity + net_debt)
    END::float8 AS roic
FROM base
"""

